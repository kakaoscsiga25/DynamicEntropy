#!/usr/bin/env python3
"""Record reference ("golden") runs of the legacy Python game logic.

The TypeScript port must reproduce these runs exactly, which proves the rules
were ported 1:1. Run from the repo root:

    python3 tools/golden.py > src/game/__tests__/golden.json

The legacy code imports Brython's `browser` module, so a tiny stub is
installed before importing it.
"""
import json
import random
import sys
import types
from pathlib import Path

LEGACY = Path(__file__).resolve().parent.parent / "legacy"
sys.path.insert(0, str(LEGACY))

browser = types.ModuleType("browser")
browser.alert = lambda *a: None
browser.window = None
local_storage = types.ModuleType("browser.local_storage")
local_storage.storage = {}
sys.modules["browser"] = browser
sys.modules["browser.local_storage"] = local_storage

TICKS = 2000
SNAPSHOT_EVERY = 10


def fresh_game():
    """Import core.data from scratch (it builds global registries on import)."""
    for name in list(sys.modules):
        if name == "core" or name.startswith("core."):
            del sys.modules[name]
    import core.data  # noqa: F401
    from core.converter import Converter
    from core.resource import Resource

    converters = Converter.converters
    resources = Resource.resources
    upgrades = [u for c in converters for u in c.upgrades]
    return converters, resources, upgrades


def num(x):
    return None if x == float("inf") else x


def recipes(lst):
    return [[r.resource.name, num(r.amount), num(r.at_least), num(r.at_most)] for r in lst]


def run(name, seed, policy, initial=None, fill_every=0):
    converters, resources, upgrades = fresh_game()
    rng = random.Random(seed)
    if initial == "full":
        for r in resources:
            r.amount = r.max_amount

    ticks = []
    for t in range(TICKS):
        actions = []
        if fill_every and t % fill_every == 0:
            for r in resources:
                r.amount = r.max_amount
            actions.append(["fill"])
        if policy == "all_on" and t == 0:
            for i, c in enumerate(converters):
                if c.is_stopped():
                    c.start()
                    actions.append(["start", i])
        elif policy == "random":
            if rng.random() < 0.08:
                i = rng.randrange(len(converters))
                c = converters[i]
                if c.is_stopped():
                    c.start()
                    actions.append(["start", i])
                else:
                    c.stop()
                    actions.append(["stop", i])
        # Buy attempts (any policy)
        buyable = [u for u in upgrades if u.isBuyable()]
        if buyable and (policy == "all_on" or rng.random() < 0.2):
            u = buyable[0] if policy == "all_on" else rng.choice(buyable)
            if u.buy():
                actions.append(["buy", u.name])

        for c in converters:
            c.update()
        for r in resources:
            r.update()

        entry = {"actions": actions}
        if t % SNAPSHOT_EVERY == SNAPSHOT_EVERY - 1 or actions:
            entry["amounts"] = [r.amount for r in resources]
            entry["states"] = [c.state for c in converters]
        ticks.append(entry)

    return {
        "name": name,
        "initial": initial,
        "ticks": ticks,
        "final": {
            "converters": [
                {"name": c.name, "needs": recipes(c.needs), "makes": recipes(c.makes)}
                for c in converters
            ],
            "bought": [u.name for u in upgrades if u.bought],
        },
    }


def main():
    converters, resources, upgrades = fresh_game()
    out = {
        "note": "Generated by tools/golden.py from legacy/ (Python v1.3.2 rules). Do not edit.",
        "stateNames": ["ok", "stopped", "noInput", "full"],  # legacy OK, STOPPED, NO_INPUT, MAX_OUTPUT
        "resources": [r.name for r in resources],
        "converters": [c.name for c in converters],
        "upgrades": [u.name for u in upgrades],
        "runs": [
            run("all_on", 0, "all_on"),
            run("random_1", 1, "random"),
            run("random_2", 2, "random"),
            run("rich_random", 3, "random", initial="full"),
            run("rich_all_on", 4, "all_on", initial="full"),
            run("refill_buy_all", 5, "all_on", fill_every=50),
        ],
    }
    json.dump(out, sys.stdout, separators=(",", ":"))


if __name__ == "__main__":
    main()
